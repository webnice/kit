package cfg

/*
module/cfg — базовое ядро приложений, построенных на github.com/webnice/kit/v4.

Пакет является singleton-дирижёром запуска приложения. Он создаёт bootstrap-конфигурацию,
разбирает командную строку и переменные окружения, регистрирует компоненты, проверяет их
зависимости и конфликты, формирует порядок запуска, управляет уровнями работы приложения
(runlevel) и аккумулирует ошибки. Полное описание архитектуры, жизненного цикла, API и
инвариантов потокобезопасности приведено в README.md.

Ключевые точки входа:

  - cfg.Get() возвращает основной интерфейс cfg.Interface.
  - cfg.Get().Gist() возвращает служебный интерфейс cfg.Essence для операций запуска.
  - module/cfg/reg.Registration регистрирует компоненты приложения на runlevel 0.
  - app.Main() является дирижёром переходов между уровнями и вызывает gist-функции cfg.

Компонентные callback-функции не вызываются с удержанием ComponentMutex: cfg копирует
список компонентов под блокировкой и выполняет пользовательский код вне неё. Это важный
инвариант: компонент может безопасно обращаться к ComponentNames(), CLI, runlevel и другим
gist-методам из своих Initiate/Do/Finalize/Preferences.

Runlevel является монотонно возрастающим значением. Значение 0 соответствует старту
приложения, значение 65535 — завершению. Targetlevel определяет уровень, до которого
дирижёр сам переключает приложение; после готовности компонентов дальнейшее переключение
может выполняться компонентами.

Стадии работы дирижёра компонентов:
  - регистрация компонентов приложения;
  - запрет регистрации компонентов приложения, переход к подготовке и выполнению компонентов;
  - проверка конфликта компонентов по правилам "КОНФЛИКТУЕТ";
  - проверка зависимости компонентов по правилам "ТРЕБУЕТ";
  - сортировка компонентов по правилу "ДО";
  - сортировка компонентов по правилу "ПОСЛЕ";
  - создание списка очерёдности выполнения компонентов и очерёдности переключения уровней работы приложения;
  - инициализация командного интерфейса CLI;
  - выполнение для всех компонентов функции Initiate() с контролем времени выполнения и прерыванием;
  - выполнение для всех компонентов функции Do() с фильтрацией по runlevel и командой запуска приложения;
  - выполнение, в обратном порядке, для всех компонент функции Finalize();
  - отображение всех накопившихся ошибок и завершение приложения с передачей большего по номеру кода возврата.

Runlevel    - текущий уровень работы приложения. Приложение при старте получает уровень 0.
              Завершает работу при переключении уровня на значение 65535. Уровень может
              изменяться только в сторону увеличения.

Targetlevel - целевой уровень работы приложения. В момент запуска приложение получает
              целевой уровень 65535, то есть выполняется и завершается. Если указано
              значение меньше 65535, приложение на этом уровне передаёт ответственность за
              дальнейшее изменение runlevel компонентам.

Уровни работы приложения:
  * 0           - [внутренний] старт, запуск init(), запуск main() приложения.
  * 1           - [внутренний] инициализация менеджера логирования.
  * 2           - [внутренний] опрос компонентов, запуск Preferences(), сбор настроек.
  * 3           - [внутренний] проверка конфликтов компонентов.
  * 4           - [внутренний] проверка зависимостей компонентов.
  * 5           - [внутренний] сортировка компонентов в соответствии с before/after.
  * 6           - [внутренний] построение шагов переключения уровня выполнения приложения.
  * 7           - [внутренний] инициализация параметров CLI и переменных окружения.
  * 8           - [внутренний] инициализация компонентов, запуск Initiate().
  * 9           - [внутренний] регистрация функций слежения за изменением runlevel.
  * 10..Target  - запуск Do() компонентов: на уровне 10, на уровне Targetlevel или на
                  пользовательских уровнях, указанных в Preferences.Runlevel.
  * 65535       - [внутренний] завершение работы приложения.
*/
