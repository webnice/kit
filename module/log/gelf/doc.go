package gelf

/*

Пакет gelf реализует клиент протокола GELF (Graylog Extended Log Format) версии 1.1
и предназначен для отправки сообщений журнала на сервер Graylog по сети.

Сообщение кодируется в формат JSON. Стандартные поля сообщения описаны структурой
Message, дополнительные поля передаются в карте Message.Keys и при кодировании
получают префикс "_", как того требует спецификация GELF. Уровни важности сообщений
соответствуют syslog severity и описаны константами SeverityEmergency - SeverityDebug.

Поддерживаются сетевые протоколы UDP, TCP и TLS:

  - UDP — протокол по умолчанию. Сообщение разбивается на чанки размером
    DefaultChunkSize (1420 байт), каждый чанк содержит магический заголовок,
    идентификатор сообщения и порядковый номер чанка. Максимальное количество
    чанков одного сообщения — 128. Соединение с сервером постоянное, устанавливается
    при создании клиента. Для протокола UDP доступно сжатие сообщений алгоритмами
    gzip и zlib.
  - TCP — сообщение отправляется целиком с нулевым байтом-разделителем.
    Сжатие сообщений не поддерживается.
  - TLS — то же, что TCP, но поверх TLS соединения. Конфигурация TLS задаётся
    опцией WithTLSConfig, по умолчанию используется конфигурация с именем сервера
    из адреса и минимальной версией TLS 1.2.

Для протоколов TCP и TLS соединение с сервером устанавливается при создании клиента
и автоматически восстанавливается при обрыве связи: количество попыток переподключения
и пауза между ними задаются опцией WithReconnect. Тайм-аут установки соединения
задаётся опцией WithDialTimeout.

Формат адреса сервера: [proto://]host:port, где proto — udp (значение по умолчанию),
tcp, tls или tcp+tls.

Клиент реализует интерфейс io.Writer: строка текста отправляется сообщением
с уровнем SeverityInfo, первая строка текста становится кратким текстом сообщения,
весь текст — полным. Это позволяет направить в сервер Graylog вывод стандартного
пакета log через log.SetOutput или io.MultiWriter.

Пример использования:

	cli, err := gelf.New("udp://127.0.0.1:12201", gelf.CompressionGzip)
	if err != nil {
		// Обработка ошибки создания клиента.
	}
	defer cli.Close()
	msg := gelf.NewMessage("backend-01", "Краткий текст сообщения", gelf.SeverityInfo)
	msg.Full = "Полный текст сообщения"
	msg.Facility = "application"
	msg.Keys["request_id"] = "b3f1c2"
	if err = cli.Send(msg); err != nil {
		// Обработка ошибки отправки сообщения.
	}

Пример отправки сообщений по протоколу TLS:

	cli, err := gelf.New("tls://graylog.example.com:12201", gelf.CompressionNone,
		gelf.WithTLSConfig(tlsConfig),
		gelf.WithReconnect(5, time.Second),
		gelf.WithDialTimeout(10*time.Second))

Пример перенаправления стандартного журнала в Graylog:

	cli, err := gelf.New("udp://127.0.0.1:12201", gelf.CompressionNone)
	if err != nil {
		// Обработка ошибки создания клиента.
	}
	log.SetOutput(io.MultiWriter(os.Stderr, cli))

*/
